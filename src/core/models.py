from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import List, Optional, Union
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Internal Dataclasses (Used by Deterministic Algorithms & Calendar Client)
# ---------------------------------------------------------------------------

@dataclass
class CalendarEvent:
    id: str
    summary: str
    start: datetime
    end: datetime
    is_all_day: bool = False


@dataclass
class TaskDraft:
    title: str
    importance: int
    urgency: int
    tags: List[str] = field(default_factory=list)


@dataclass(frozen=True)
class TimeSlot:
    start: datetime
    end: datetime
    duration_minutes: int


# ---------------------------------------------------------------------------
# Pydantic Schemas (Used for LLM Structured Outputs & Ingestion Validation)
# ---------------------------------------------------------------------------

class EventType(str, Enum):
    LECTURE = "lecture"
    MEETING = "meeting"
    ROUTINE = "routine"
    EVALUATIVE = "evaluative"
    OTHERS = "others"


class PriorityCategory(str, Enum):
    URGENT = "urgent"
    IMPORTANT = "important"
    ROUTINE = "routine"
    LOW_PRIORITY = "low_priority"


class DateTimeAnchor(BaseModel):
    dateTime: Optional[str] = Field(
        default=None,
        description="ISO 8601 local datetime (YYYY-MM-DDTHH:MM), or null if unstated.",
    )


class ScoredTask(BaseModel):
    title: str = Field(
        description="Clean, normalized task or event title."
    )
    event_type: EventType = Field(
        description="Categorical type of the event or activity."
    )
    start: DateTimeAnchor = Field(
        description="Explicit start time anchor, or null if flexible."
    )
    end: DateTimeAnchor = Field(
        description="Explicit deadline or end time anchor, or null if flexible."
    )
    estimated_duration: int = Field(
        ge=1,
        description="Realistic duration in minutes (must be at least 1).",
    )
    importance: int = Field(
        ge=1,
        le=5,
        description="Significance and impact rating from 1 (trivial) to 5 (critical).",
    )
    urgency: int = Field(
        ge=1,
        le=5,
        description="Time sensitivity rating from 1 (someday/flexible) to 5 (due today/ASAP).",
    )
    is_movable: bool = Field(
        description="False for fixed meetings or synchronized classes; True for self-directed work.",
    )
    priority_category: PriorityCategory = Field(
        description="High-level category derived from importance, urgency, and event_type.",
    )
    scoring_rationale: str = Field(
        description="One concise sentence explaining why these scores were assigned.",
    )


class ScoredTaskList(BaseModel):
    tasks: List[ScoredTask] = Field(
        description="Complete list of prioritized and scored tasks."
    )


class TimeHorizonOutput(BaseModel):
    start_datetime: str = Field(
        description="ISO 8601 start datetime with timezone offset (e.g. 2026-10-17T17:12:00+05:30), representing the scheduling start boundary."
    )
    end_datetime: str = Field(
        description="ISO 8601 end datetime with timezone offset (e.g. 2026-10-23T23:59:59+05:30), representing the End of Day (23:59:59) of the latest date mentioned across all tasks/events."
    )
    latest_event_title: Optional[str] = Field(
        default=None,
        description="Title or description of the latest task/event that determined the horizon end date."
    )
    reasoning: Optional[str] = Field(
        default=None,
        description="Brief explanation of how the start and end dates were determined from the input notes."
    )


# ---------------------------------------------------------------------------
# Scheduling Placement Models (Generated by Optimizer)
# ---------------------------------------------------------------------------

@dataclass
class PlacedTask:
    task: Union[ScoredTask, TaskDraft]
    start: datetime
    end: datetime
    priority_score: float


@dataclass
class UnplacedTask:
    task: Union[ScoredTask, TaskDraft]
    reason: str
    priority_score: float


@dataclass
class SchedulePlan:
    placed_tasks: List[PlacedTask]
    unplaced_tasks: List[UnplacedTask]
    remaining_slots: List[TimeSlot]
    existing_events: List[CalendarEvent] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Preference & Habit Profiles (Used for Continuous Gradient Optimization)
# ---------------------------------------------------------------------------

class PreferenceProfile(BaseModel):
    profile_name: str = Field(description="Unique identifier for the profile or activity category.")
    updated_count: int = Field(default=0, ge=0, description="Number of observed task placements recorded in this profile.")
    hourly_weights: List[float] = Field(
        default_factory=lambda: [0.0] * 24,
        description="24 hourly weights (0.0 to 1.0) representing preference/willingness for hours 00:00 through 23:00.",
    )
    description: Optional[str] = Field(
        default=None,
        description="Optional human-readable description or notes about the profile.",
    )

    def get_weight(self, hour: int) -> float:
        """Returns weight for a specific hour (0-23)."""
        if 0 <= hour < 24:
            return self.hourly_weights[hour]
        raise ValueError(f"Hour must be between 0 and 23, got {hour}")


class UpdatedCurveResponse(BaseModel):
    hourly_weights: List[float] = Field(
        description="Updated 24 hourly weights (strictly 0.0 to 1.0) for hours 00:00 through 23:00."
    )
    update_rationale: str = Field(
        description="One concise sentence explaining how the curve was adjusted based on the scheduled event."
    )

